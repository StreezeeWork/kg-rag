def write_jsonl(path: Path, records: list[dict]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records), encoding="utf-8")
    return path


def train_records(split: str | None = "train") -> list[dict]:
    """Копия обучающих записей; ``split=None`` — как в частях (data/eval/train_parts), без поля split."""
    return [dict(record, split=split) if split else dict(record) for record in TRAIN_RECORDS]
